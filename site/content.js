(() => {
  'use strict';
  const archive = window.GEOGEEK_ARCHIVE;
  const buildLocale = lang => {
    const ui = archive.locales?.[lang]?.ui || archive.locales?.en?.ui || {};
    const itemFor = record => ({ id: record.id, ...(record.data || {}), ...(record.text?.[lang] || record.text?.en || {}) });
    const byKind = kind => archive.records.filter(record => record.kind === kind).map(itemFor);
    const atlasLayout = archive.records.filter(record => record.atlas).map(record => ({
      ref: record.ref,
      ...Object.fromEntries(Object.entries(record.atlas || {}).filter(([key]) => key !== 'text')),
      ...(record.atlas?.text?.[lang] || record.atlas?.text?.en || {}),
      traceLinks: [...(record.relations?.trace || [])]
    }));
    return { ui, notes: byKind('notes'), lab: byKind('lab'), elsewhere: byKind('elsewhere'), atlasLayout };
  };
  window.GEOGEEK_DATA = { en: buildLocale('en'), zh: buildLocale('zh') };
})();
