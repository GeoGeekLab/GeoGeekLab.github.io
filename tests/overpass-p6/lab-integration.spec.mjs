import {test,expect} from '@playwright/test'
const ids=['l04','l05','l06','l10','l11','l12','l13','l07','l08','l09','l14','l15','l16']
test('P6 first-paint Lab has fourteen source-level cards, even with JavaScript disabled',async({browser})=>{
 const context=await browser.newContext({javaScriptEnabled:false})
 const page=await context.newPage()
 try{
  await page.goto('http://127.0.0.1:4173/lab.html',{waitUntil:'domcontentloaded'})
  await expect(page.locator('#labList .project-card')).toHaveCount(14)
  for(const id of ids)await expect(page.locator('#'+id)).toBeAttached()
  const card=page.locator('#l17')
  await expect(card).toBeAttached()
  await expect(card.getByRole('link',{name:'Open OVERPASS instrument'})).toHaveAttribute('href','/overpass/?from=lab')
  await expect(card.locator('iframe')).toHaveCount(0)
 }finally{await context.close()}
})
test('Lab card uses an actual render and opens OVERPASS, which returns to the same record',async({page},info)=>{
 test.setTimeout(145000)
 await page.goto('/lab.html',{waitUntil:'domcontentloaded'})
 const card=page.locator('#l17')
 await expect(card).toBeAttached({timeout:30000})
 await expect(page.locator('#labList .project-card')).toHaveCount(14)
 const preview=card.locator('img[src*="overpass.jpg"]')
 await preview.scrollIntoViewIfNeeded()
 await expect.poll(()=>preview.evaluate(img=>img.complete&&img.naturalWidth>0),{timeout:20000}).toBe(true)
 await page.screenshot({path:info.outputPath('lab-overpass-card.png'),fullPage:true})
 await card.getByRole('link',{name:'Open OVERPASS instrument'}).click()
 await expect(page).toHaveURL(/\/overpass\/\?from=lab/)
 await expect(page).toHaveTitle(/OVERPASS/i)
 await expect(page.locator('#boot-static')).toHaveCount(0,{timeout:45000})
 const back=page.getByRole('link',{name:'Back to GeoGeek Lab'})
 await expect(back).toBeVisible({timeout:25000})
 await page.screenshot({path:info.outputPath('overpass-from-lab.png'),fullPage:true})
 await back.click()
 await expect(page).toHaveURL(/\/lab\.html#l17$/)
 await expect(page.locator('#l17')).toBeAttached()
})
test('The old Orbit instrument keeps its existing modal lifecycle and data source',async({page})=>{
 test.setTimeout(110000)
 await page.goto('/lab.html',{waitUntil:'domcontentloaded'})
 const orbit=page.locator('#l04 [data-instrument="orbit"]').first()
 await expect(orbit).toBeVisible({timeout:25000})
 await orbit.click()
 const dialog=page.locator('#instrumentDialog')
 await expect(dialog).toHaveAttribute('open','',{timeout:60000})
 await expect(page.locator('#instrumentStage')).not.toBeEmpty()
 await page.locator('#instrumentClose').click()
 await expect(dialog).not.toHaveAttribute('open','',{timeout:12000})
 await expect(page.locator('#l17')).toBeAttached()
})
test('Direct OVERPASS deep links preserve scientific coordinates and use a non-invasive return',async({page},info)=>{
 test.setTimeout(140000)
 const original='/overpass/?q=36.4837,130.4737&n=Selected%20location'
 await page.goto(original,{waitUntil:'domcontentloaded'})
 await expect(page.locator('#boot-static')).toHaveCount(0,{timeout:45000})
 const back=page.getByRole('link',{name:'Back to GeoGeek Lab'})
 await expect(back).toBeVisible({timeout:30000})
 await expect(back).toHaveAttribute('href','/lab.html#l17')
 const url=new URL(page.url())
 expect(url.searchParams.get('q')).toBe('36.4837,130.4737')
 await page.screenshot({path:info.outputPath('overpass-direct.png'),fullPage:true})
 // The original Watched About overlay owns focus and stays visually unobstructed.
 await page.getByRole('button',{name:/How this works/i}).click()
 await expect(page.getByRole('dialog').first()).toBeVisible()
 await expect(back).toBeHidden()
 await page.keyboard.press('Escape')
 await expect(page.getByRole('dialog').first()).toHaveCount(0,{timeout:10000})
 await expect(back).toBeVisible()
 await back.click()
 await expect(page).toHaveURL(/\/lab\.html#l17$/)
 await page.goBack({waitUntil:'domcontentloaded'})
 const restored=new URL(page.url())
 expect(restored.pathname).toBe('/overpass/')
 const [lat,lon]=(restored.searchParams.get('q')||'').split(',').map(Number)
 expect(Math.abs(lat-36.4837)).toBeLessThan(0.001)
 expect(Math.abs(lon-130.4737)).toBeLessThan(0.001)
 expect(restored.searchParams.get('n')).toBe('Selected location')
})
