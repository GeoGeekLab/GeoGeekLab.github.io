import {test,expect} from '@playwright/test'
test('P7 GeoGeek archive owns the l17 record and its published detail page',async({page},info)=>{
 await page.goto('/lab.html',{waitUntil:'domcontentloaded'})
 await expect(page.locator('#labList .project-card')).toHaveCount(14)
 const item=page.locator('#l17')
 await expect(item).toHaveAttribute('data-record-ref','lab:l17')
 await expect(item.locator('[data-instrument-route]')).toHaveAttribute('href','/overpass/?from=lab')
 await expect(item.locator('[data-overpass-lab-card="p6"]')).toHaveCount(0)
 await item.getByRole('link',{name:/Read OVERPASS record/i}).click()
 await expect(page).toHaveURL(/\/records\/lab-l17\.html/)
 await expect(page.getByText(/Watched by Armaan Gupta/i).first()).toBeVisible()
 await expect(page.getByRole('link',{name:/OPEN OVERPASS/i}).first()).toHaveAttribute('href','/overpass/?from=record')
 await page.screenshot({path:info.outputPath('p7-source-record.png'),fullPage:true})
})
test('P7 return to source-owned l17 keeps original Watched About and canonical entry',async({page},info)=>{
 test.setTimeout(140000)
 await page.goto('/overpass/?q=43.4723,-80.5449&n=Waterloo',{waitUntil:'domcontentloaded'})
 await expect(page.locator('#boot-static')).toHaveCount(0,{timeout:60000})
 await expect(page.getByRole('link',{name:'Back to GeoGeek Lab'})).toBeVisible()
 await page.getByRole('link',{name:'Back to GeoGeek Lab'}).click()
 await expect(page).toHaveURL(/\/lab\.html#l17$/)
 await expect(page.locator('#l17')).toBeAttached()
 const card=page.locator('#l17 .project-visual-overpass img')
 await expect.poll(()=>card.evaluate(x=>x.complete&&x.naturalWidth>0)).toBe(true)
 await page.screenshot({path:info.outputPath('p7-source-lab.png'),fullPage:true})
})
